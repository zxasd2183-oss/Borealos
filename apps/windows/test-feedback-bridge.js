const assert = require("node:assert/strict");
const fs = require("node:fs");

const main = fs.readFileSync(require.resolve("./main.js"), "utf8");
const preload = fs.readFileSync(require.resolve("./feedback-preload.js"), "utf8");
const pkg = require("./package.json");
const { createTrustedOriginCheck } = require("./trusted-origin");
assert.match(main, /feedback:capture-current-window/);
assert.match(main, /senderFrame\.url/);
assert.match(main, /isTrustedBorealosUrl/);
assert.match(main, /will-navigate/);
assert.match(main, /will-redirect/);
assert.match(main, /certificate-error/);
assert.match(main, /event\.preventDefault\(\)/);
assert.match(main, /callback\(true\)/);
assert.match(main, /isTrustedBorealosUrl\(url\)/);
assert.match(main, /https:\/\/borealos\.dev/);
assert.doesNotMatch(main, /url\.startsWith\(APP_URL\).*action: 'allow'/);
assert.match(main, /capturePage\(\)/);
assert.match(main, /toPNG\(\)/);
assert.match(preload, /BorealosFeedbackBridge/);
assert.match(preload, /ipcRenderer\.invoke\("feedback:capture-current-window"\)/);
assert.ok(pkg.build.files.includes("feedback-preload.js"));
assert.ok(pkg.build.files.includes("trusted-origin.js"));
const trusted = createTrustedOriginCheck("https://borealos.dev,http://127.0.0.1:18790");
assert.equal(trusted("https://borealos.dev/page"), true);
assert.equal(trusted("http://127.0.0.1:18790/dev"), true);
assert.equal(trusted("https://borealos.dev.evil.example/"), false);
assert.equal(trusted("https://evil.example/?next=https://borealos.dev"), false);
console.log("windows feedback bridge checks passed");
