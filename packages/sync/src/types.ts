// ============================================================================
// Awareness 协作状态
// ============================================================================

/**
 * Awareness 状态
 *
 * 描述单个用户在协作会话中的实时状态，包括身份信息、光标位置、
 * 选区范围与最后活跃时间。用于实现多人光标、在线状态等功能。
 */
export interface AwarenessState {
  /** 用户 ID */
  userId: string;
  /** 用户名 */
  username: string;
  /** 用户区分色（十六进制颜色值） */
  color: string;
  /** 当前正在编辑的文件路径 */
  filePath?: string;
  /** 光标所在行号（从 1 开始） */
  line?: number;
  /** 光标所在列号（从 1 开始） */
  column?: number;
  /** 选区起始偏移量 */
  selectionStart?: number;
  /** 选区结束偏移量 */
  selectionEnd?: number;
  /** 最后活跃时间（Unix 毫秒时间戳） */
  lastActive: number;
}

// ============================================================================
// 同步文档状态
// ============================================================================

/**
 * 同步文档状态
 *
 * 描述单个文件在某一时点的快照状态，用于全量状态同步与冲突检测。
 */
export interface DocumentState {
  /** 所属项目 ID */
  projectId: string;
  /** 文件相对路径 */
  filePath: string;
  /** 文件文本内容 */
  content: string;
  /** 文档版本号（每次更新自增） */
  version: number;
  /** 最后修改时间（ISO 8601 字符串） */
  lastModified: string;
  /** 最后修改者用户 ID */
  modifiedBy?: string;
}

// ============================================================================
// 同步更新消息
// ============================================================================

/**
 * 同步更新消息
 *
 * 客户端与服务端之间通过 WebSocket 传递的统一消息格式。
 * 根据类型字段区分：文档增量更新、Awareness 状态更新、全量文档状态。
 */
export interface SyncUpdate {
  /** 消息类型 */
  type: 'update' | 'awareness' | 'state';
  /** 所属项目 ID */
  projectId: string;
  /** 关联文件路径（update / state 类型时存在） */
  filePath?: string;
  /** 文档增量更新（CRDT 二进制编码，update 类型时存在） */
  update?: Uint8Array;
  /** Awareness 状态（awareness 类型时存在） */
  awareness?: AwarenessState;
  /** 文档全量状态（state 类型时存在） */
  state?: DocumentState;
  /** 消息时间戳（ISO 8601 字符串） */
  timestamp: string;
}

// ============================================================================
// 同步配置
// ============================================================================

/**
 * 同步配置
 *
 * SyncClient 初始化所需的全部配置项。
 */
export interface SyncConfig {
  /** WebSocket 服务端地址，例如 'ws://localhost:3001/sync' */
  wsURL: string;
  /** 项目 ID（同步房间标识） */
  projectId: string;
  /** 当前用户 ID */
  userId: string;
  /** 当前用户名 */
  username: string;
  /** 重连基础延迟（毫秒） */
  reconnectDelay: number;
  /** 最大重连次数 */
  maxReconnect: number;
  /** 心跳间隔（毫秒） */
  heartbeatInterval: number;
}

// ============================================================================
// 同步事件
// ============================================================================

/**
 * 同步事件
 *
 * SyncClient 对外暴露的事件类型，供 UI 层订阅以响应同步状态变化。
 */
export interface SyncEvent {
  /** 事件类型 */
  type: 'connected' | 'disconnected' | 'synced' | 'error' | 'awareness' | 'update';
  /** 事件数据 */
  data?: unknown;
}
